class Food:
  def __init__(self, n, p, prep_time, dis = 0):
    self.name = n
    self.price = p
    self.preparation_time = prep_time
    self.discount = dis

  def final_price(self):
    return self.price - (self.price * self.discount / 100)


# Pizza
class Pizza(Food):
  pass

# Burger
class Burger(Food):
  pass

# Drink
class Drink(Food):
  pass


# order

class Order:
  def __init__(self):
    self.items = []
  def add_food(self, food):
    self.items.append(food)
  def remove_food(self, food):
    self.items.remove(food)
  def check_items(self):
    for food in self.items:
      print(food.name, "-", food.final_price())
  def calculate_bill(self):
    total = 0
    for food in self.items:
      total += food.final_price()
    return total

  def place_order(self):
    print("Order placed successfully")
    print("Total_bill: ", self.calculate_bill())




# food items
burger = Burger("Burger", 500, 15, 10)
pizza = Pizza("Pizza", 1200, 25, 5)
drink = Drink("Drink", 200, 5, 0)


# customer order
order = Order()

order.add_food(burger)
order.add_food(burger)

order.add_food(pizza)

order.add_food(drink)
order.add_food(drink)


print("Order items:")
order.check_items()
print("Bill:")
order.place_order()