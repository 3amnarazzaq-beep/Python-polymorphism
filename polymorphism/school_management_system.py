class Person:
  def __init__(self, name):
    self.name = name

class Student(Person):
  def __init__(self, name, roll_no, student_type):
    super().__init__(name)
    self.roll_no = roll_no
    self.student_type = student_type
    self.marks = []

  def add_marks(self):
    print("Enter marks of 5 subjects")
    for i in range(5):
      mark = float(input(f"subject {i + 1}: "))
      self.marks.append(mark)

  def calculate_result(self):
    total = sum(self.marks)
    percentage = total/5

    if self.student_type == "Scholarship":
      if percentage >= 80:
        grade = "A"
      elif percentage >= 70:
        grade = "B"
      elif percentage >= 60:
        grade = "C"
      else:
        grade = "F"
        print("Fail")

    else:
      if percentage >= 90:
        grade = "A"
      elif percentage >= 80:
        grade = "B"
      elif percentage >= 70:
        grade = "C"
      elif percentage >= 60:
        grade = "D"
      else:
        grade = "F"
        print("Fail")

    print(" ////// Student Result////// ")
    print("Name: ", self.name)
    print("Roll_no: ", self.roll_no)
    print("Student_type: ", self.student_type)
    print("Marks of subjects: ")
    for i, mark in enumerate(self.marks, 1):
      print(f"subject {i}: {mark}")
    print("Total marks:", total)
    print("Percentage: ", percentage, "%")
    print("Grade: ", grade)

