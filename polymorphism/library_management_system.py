# Parent Class
class Book:
    def __init__(self, title, author):
        self.title = title
        self.author = author
        self.available = True

    def access(self):
        print("Accessing book...")


# EBook
class EBook(Book):
    def access(self):
        print("You can read this book online.")


# PrintedBook
class PrintedBook(Book):
    def access(self):
        print("You can read this book physically.")


# AudioBook
class AudioBook(Book):
    def access(self):
        print("You can listen to this book.")


# Library Class
class Library:
    def __init__(self):
        self.books = []

    def add_book(self, book):
        self.books.append(book)

    def search_book(self, title):
        for book in self.books:
            if book.title.lower() == title.lower():
                print("Book found:", book.title)
                return book

        print("Book not found.")
        return None

    def issue_book(self, title):
        book = self.search_book(title)

        if book:
            if book.available:
                book.available = False
                print("Book issued successfully!")
                book.access()
            else:
                print("Book is already issued.")

    def return_book(self, title):
        book = self.search_book(title)

        if book:
            book.available = True
            print("Book returned successfully!")


# Create books
book1 = EBook("Python Programming", "Ali")
book2 = PrintedBook("History of Pakistan", "Ahmed")
book3 = AudioBook("English Learning", "Sara")

# Create library
library = Library()

library.add_book(book1)
library.add_book(book2)
library.add_book(book3)


# Student searches and issues programming book
library.issue_book("Python Programming")