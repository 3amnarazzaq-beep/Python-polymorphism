# Parent Class
class Person:
    def __init__(self, name):
        self.name = name

class Doctor(Person):
    def __init__(self, name, specialty, fee):
        super().__init__(name)
        self.specialty = specialty
        self.fee = fee

    def consultation_fee(self):
        return self.fee

class Nurse(Person):
    pass

class Patient(Person):
    def book_appointment(self, doctor):
        print(self.name, "booked appointment with Dr.", doctor.name)
        print("Consultation Fee: Rs.", doctor.consultation_fee())


class Hospital:
    def __init__(self):
        self.doctors = []
        self.appointments = []

    def add_doctor(self, doctor):
        self.doctors.append(doctor)

    def display_doctors(self):
        print("Available Doctors:")
        for doctor in self.doctors:
            print(doctor.name, "-", doctor.specialty,
                  "- Fee: Rs.", doctor.fee)

    def book_appointment(self, patient, doctor):
        self.appointments.append((patient, doctor))
        patient.book_appointment(doctor)

    def cancel_appointment(self, patient, doctor):
        appointment = (patient, doctor)

        if appointment in self.appointments:
            self.appointments.remove(appointment)
            print("Appointment cancelled.")
        else:
            print("Appointment not found.")

    def display_appointments(self):
        print("\nAppointments:")
        for patient, doctor in self.appointments:
            print(patient.name, "with Dr.", doctor.name)

    def generate_bill(self, doctor):
        print("Hospital Bill")
        print("Doctor:", doctor.name)
        print("Consultation Fee: Rs.", doctor.consultation_fee())



h = Hospital()

d1 = Doctor("Ali", "Cardiologist", 3000)
d2 = Doctor("Ahmed", "Dermatologist", 2000)

n1 = Nurse("Sara")

p1 = Patient("Amna")

# Add doctors
h.add_doctor(d1)
h.add_doctor(d2)

# Display available doctors
h.display_doctors()

# Book appointment
print()
h.book_appointment(p1, d1)

# Display appointments
h.display_appointments()

# Generate bill
print()
h.generate_bill(d1)

# Cancel appointment
print()
h.cancel_appointment(p1, d1)