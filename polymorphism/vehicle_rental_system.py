'''
Vehicle Rental System
A rental company provides cars, bikes, and vans.
Rent vehicle, return vehicle, calculate rent.
Display all available vehicles.
Vehicle → Car, Bike, Van.
Each vehicle calculates rent differently.
A customer wants to rent a vehicle for 3 days. The system checks available
vehicles and calculates the rental price based on the selected vehicle type.
'''

class Vehicle:
    def __init__(self, name, rent_per_day):
        self.name = name
        self.rent_per_day = rent_per_day
        self.available = True

    def calculate_rent(self, days):
        return self.rent_per_day * days


class Car(Vehicle):
    def calculate_rent(self, days):
        return self.rent_per_day * days


class Bike(Vehicle):
    def calculate_rent(self, days):
        return self.rent_per_day * days


class Van(Vehicle):
    def calculate_rent(self, days):
        return self.rent_per_day * days


# Vehicles
car = Car("Toyota Car", 5000)
bike = Bike("Honda Bike", 2000)
van = Van("Toyota Van", 7000)

vehicles = [car, bike, van]


# Display available vehicles
print("Available Vehicles:")

for vehicle in vehicles:
    if vehicle.available:
        print(vehicle.name)


# Rent Vehicle
selected_vehicle = car
days = 3

if selected_vehicle.available:
    print("\nVehicle Rented:", selected_vehicle.name)

    # Calculate rent
    total_rent = selected_vehicle.calculate_rent(days)
    print("Total Rent:", total_rent)

    selected_vehicle.available = False


# Return Vehicle
selected_vehicle.available = True
print("\nVehicle Returned:", selected_vehicle.name)