class Product:
  def __init__(self, n, p):
    self.name = n
    self.price = p

  def dis(self):
    return 0

# mobile
class Mobile(Product):
  def dis(self):
    return self.price * 0.10

# laptop
class Laptop(Product):
  def dis(self):
    return self.price * 0.15

# clothing
class Clothing(Product):
  def dis(self):
    return self.price * 0.20


# Cart
class Cart:
  def __init__(self):
    self.products = []

  def add_products(self, product):
    self.products.append(product)

  def remove_products(self, product):
    self.products.remove(product)

  def total(self):
    total = 0
    for product in self.products:
      total += product.price - product.dis()

    return total


# customer buys a laptop and a shirt
laptop = Laptop("Laptop", 10000)
shirt = Clothing("Shirt", 4000)


cart = Cart()
cart.add_products(laptop)
cart.add_products(shirt)
print(cart.products)




print("Final bill: ", cart.total())